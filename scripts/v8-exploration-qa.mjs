async function geometry(name) {
    const result = await page.evaluate(() => {
        const root = document.querySelector('main');
        const viewport = innerWidth;
        const elements = [...root.querySelectorAll('button, input, select, textarea, summary, h1, h2, h3')]
            .filter(element => element.getClientRects().length && getComputedStyle(element).visibility !== 'hidden');
        const outside = elements.filter(element => {
            const bounds = element.getBoundingClientRect();
            return bounds.left < -1 || bounds.right > viewport + 1;
        }).map(element => element.textContent?.slice(0, 70));
        const controls = [...root.querySelectorAll('select, fieldset button')].filter(element => element.getClientRects().length).map(element => {
            const box = element.getBoundingClientRect();
            return { y: box.y, height: box.height };
        });
        return { viewport, scrollWidth: document.documentElement.scrollWidth, outside, controls };
    });
    assert.ok(result.scrollWidth <= result.viewport, `${name}: document overflow ${JSON.stringify(result)}`);
    assert.deepEqual(result.outside, [], `${name}: element overflow`);
    if (result.controls.length === 3 && name.startsWith('Market')) {
        assert.ok(Math.abs(result.controls[0].y - result.controls[1].y) <= 2, `${name}: control alignment`);
        assert.ok(result.controls.every(control => control.height >= 40), `${name}: control height`);
    }
    checks.push({ name, ...result });
}
async function shot(name) {
    // Anchor fixed elements to the top viewport before a full-page capture.
    await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
    await page.locator('dialog[open]').evaluateAll(dialogs => dialogs.forEach(dialog => dialog.scrollTo({ top: 0, behavior: 'instant' })));
    await page.screenshot({ path: `${output}/${name}.png`, fullPage: !(await page.locator('dialog[open]').count()), caret: 'initial' });
}
async function dismissInheritedNotice() {
    const dismiss = page.getByRole('button', { name: 'Dismiss notice', exact: true });
    if (await dismiss.isVisible()) await dismiss.click();
}
